import { test, expect } from "@playwright/test";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const root = fileURLToPath(new URL("../../", import.meta.url));
const planPath = path.join(root, "docs/presentation/capture-plan.json");

function emit(name, bytes) {
  const encoded = bytes.toString("base64");
  console.log("SAFESPACE_ASSET_BEGIN " + name);
  for (let i = 0; i < encoded.length; i += 8192) {
    console.log("SAFESPACE_ASSET_CHUNK " + encoded.slice(i, i + 8192));
  }
  console.log("SAFESPACE_ASSET_END");
}

async function settleWorkspace(page) {
  await page.mouse.move(0, 0);
  await page.locator("#workspace").evaluate((element) => {
    const top = element.getBoundingClientRect().top + window.scrollY;
    window.scrollTo(0, top);
  });
  await page.evaluate(async () => {
    await new Promise((resolve) => requestAnimationFrame(resolve));
    await new Promise((resolve) => requestAnimationFrame(resolve));
  });
}

test("capture actual app and format documentation", async ({ page }) => {
  test.setTimeout(60000);
  const files = JSON.parse(readFileSync(planPath, "utf8")).files;
  for (const [name, content] of Object.entries(files)) {
    const target = path.join(root, name);
    mkdirSync(path.dirname(target), { recursive: true });
    const output = name.endsWith(".md")
      ? await format(content, { parser: "markdown" })
      : content;
    writeFileSync(target, output);
  }
  const errors = [];
  const sensing = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("request", (request) => {
    const url = request.url();
    const isSensing = /4174|storage.googleapis.com|coco-ssd/.test(url);
    if (isSensing) sensing.push(url);
  });
  await page.addInitScript(() => {
    Object.defineProperty(navigator, "mediaDevices", {
      value: {
        getUserMedia() {
          throw new Error("Real sensing is disabled");
        },
      },
    });
    Object.defineProperty(navigator, "bluetooth", {
      value: {
        requestDevice() {
          throw new Error("Real sensing is disabled");
        },
      },
    });
    localStorage.clear();
  });
  await page.route("http://127.0.0.1:4174/**", (route) => route.abort());
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.goto("/");
  const start = page.getByRole("button", { name: "Start inspection" });
  await start.click();
  await page.evaluate(() => document.fonts.ready);
  await settleWorkspace(page);
  const desktop = "docs/media/camera-workspace-desktop.png";
  await page.screenshot({ path: path.join(root, desktop), fullPage: false });
  await page.setViewportSize({ width: 390, height: 1250 });
  const checklist = page.getByRole("button", {
    name: "Safety Checklist",
    exact: true,
  });
  await checklist.click();
  await expect(checklist).toHaveAttribute("aria-pressed", "true");
  await settleWorkspace(page);
  await expect(page.getByRole("checkbox")).toHaveCount(6);
  await expect(page.getByRole("checkbox", { checked: true })).toHaveCount(0);
  const mobile = "docs/media/checklist-mobile.png";
  await page.screenshot({ path: path.join(root, mobile), fullPage: false });
  expect(errors).toEqual([]);
  expect(sensing).toEqual([]);
  const capture = {
    capturedAt: new Date().toISOString(),
    sourceAppRevision: "d3af9676840c8e3006067e80887ca75645244981",
    captureCommit: process.env.GITHUB_SHA,
    workflowRun: process.env.GITHUB_RUN_ID,
    desktop: [1440, 1100],
    mobile: [390, 1250],
    browser: page.context().browser().version(),
    camera: "off",
    checklist: "0/6",
    realSensing: false,
    pageErrors: errors,
    sensingRequests: sensing,
  };
  const receipt = "docs/media/capture-record.json";
  const receiptJson = await format(JSON.stringify(capture), {
    parser: "json",
  });
  writeFileSync(path.join(root, receipt), receiptJson);
  const provenance = [
    "# SafeSpace media provenance",
    "",
    "These are actual full-viewport captures of the existing app in Chromium, generated by a temporary read-only CI capture harness after the local workspace became unavailable. They are not mockups or detection evidence.",
    "",
    "- Desktop: 1440 × 1100, camera workspace after Start inspection; camera off, no observations.",
    "- Narrow screen: 390 × 1250, checklist selected with 0/6 checked; browser viewport emulation, not a physical-phone check.",
    "- Source app: d3af967; capture commit, browser version and timestamp are in [capture-record.json](capture-record.json).",
    "- Real camera/BLE APIs were replaced with throwing adapters; helper requests were blocked. Capture asserted zero sensing requests and page errors.",
    "- Reduced motion was enabled. No imagery of a room, real nearby identifiers or network inventory was collected.",
    "",
    "The two SVG banners are original decorative artwork using SafeSpace's existing midnight/violet/cyan palette and shield motif. Their rings are not scan results. They include accessible titles/descriptions and reference no external assets.",
    "",
    "No logos, screenshots, artwork or code were copied from the reference profile. See [presentation sources](../presentation/README.md).",
    "",
    "The temporary capture harness and plan were removed once the reviewed assets were committed. Historical quality measurements remain unchanged; this documentation capture is not a new model or physical-device evaluation.",
    "",
  ].join("\n");
  const mediaReadme = "docs/media/README.md";
  const formatted = await format(provenance, { parser: "markdown" });
  writeFileSync(path.join(root, mediaReadme), formatted);
  const assetNames = [...Object.keys(files), desktop, mobile, receipt];
  assetNames.push(mediaReadme);
  for (const name of assetNames) {
    emit(name, readFileSync(path.join(root, name)));
  }
  for (const [name, width, height] of [
    ["safespace-banner.svg", 1600, 480],
    ["safespace-banner-mobile.svg", 768, 800],
  ]) {
    await page.setViewportSize({ width, height });
    const svg = readFileSync(path.join(root, "docs/media", name), "utf8");
    const markup = "<style>html,body{margin:0}</style>" + svg;
    await page.setContent(markup);
    emit("preview-" + name + ".png", await page.screenshot());
  }
});
